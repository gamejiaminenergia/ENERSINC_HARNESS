#!/usr/bin/env node
/**
 * Regenerate the ENERSINC logo React component from the source SVG.
 *
 * Reads the source SVG, drops the C2PA metadata block and the full-canvas
 * white backdrop, and emits a typed React component that inlines the remaining
 * paths (so the client bundle needs no asset pipeline).
 *
 *   node scripts/brand/gen-logo.mjs
 *   node scripts/brand/gen-logo.mjs --svg branding/enersinc-logo.svg --out branding/dsh-client-ui-brand-enersinc/src/client/EnersincLogo.tsx
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..', '..')

function arg(name, fallback) {
  const index = process.argv.indexOf(`--${name}`)
  return index === -1 ? fallback : process.argv[index + 1]
}

const svgPath = resolve(repoRoot, arg('svg', 'branding/enersinc-logo.svg'))
const outPath = resolve(
  repoRoot,
  arg('out', 'branding/dsh-client-ui-brand-enersinc/src/client/EnersincLogo.tsx'),
)

/** Escape a string for use inside a double-quoted JS/JSX attribute. */
const attr = (value) => value.replaceAll('&', '&amp;').replaceAll('"', '&quot;')

function build(source) {
  const withoutMetadata = source
    .replace(/<metadata>[\s\S]*?<\/metadata>/g, '')
    .replace(/\sxmlns:c2pa="[^"]*"/g, '')

  const paths = [...withoutMetadata.matchAll(/<path\b[^>]*\/>/g)].map((match) => match[0])
  // Drop the full-canvas white background (its `d` starts the 2560-wide rect).
  const kept = paths.filter((path) => !path.includes('M0 0 C844.8 0 1689.6 0 2560 0'))
  if (kept.length === 0) throw new Error(`no drawable paths found in ${svgPath}`)

  const jsxPaths = kept.map((path) => {
    const d = (path.match(/ d="([^"]*)"/) || [])[1]
    const fill = (path.match(/ fill="([^"]*)"/) || [])[1] || 'currentColor'
    const transform = (path.match(/ transform="([^"]*)"/) || [])[1]
    const attrs = [`d="${attr(d)}"`, `fill="${fill}"`]
    if (transform) attrs.push(`transform="${attr(transform)}"`)
    if (/fill-rule="nonzero"/.test(path)) attrs.push('fillRule="nonzero"')
    return `      <path ${attrs.join(' ')} />`
  }).join('\n')

  const clean = `<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 2560 472" width="2560" height="472">\n${kept
    .map((path) => '  ' + path)
    .join('\n')}\n</svg>\n`

  const tsx = `import type { CSSProperties } from 'react'

/**
 * ENERSINC brand mark inlined as SVG paths (viewBox 0 0 2560 472).
 * Generated by scripts/brand/gen-logo.mjs — edit branding/enersinc-logo.svg
 * and re-run the generator instead of editing this file by hand.
 */
export function EnersincLogo({
  height = 24,
  className,
  style,
}: {
  height?: number
  className?: string
  style?: CSSProperties
}) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 2560 472"
      height={height}
      width={(2560 / 472) * height}
      className={className}
      style={style}
      role="img"
      aria-label="ENERSINC"
    >
${jsxPaths}
    </svg>
  )
}
`
  return { clean, tsx, kept: kept.length }
}

const source = readFileSync(svgPath, 'utf8')
const { clean, tsx, kept } = build(source)
writeFileSync(svgPath, clean)
writeFileSync(outPath, tsx)
console.log(`[brand] regenerated ${outPath} (${kept} paths) from ${svgPath}`)
